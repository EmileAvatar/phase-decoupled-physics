# PART 7: SUDOKU CONSISTENCY CHECK (12 tests)
# ===========================================================================

def sudoku_checks(rw, s1, s2, s3, s4, s5, s6):
    rw.section("SUDOKU CONSISTENCY CHECK")

    passes = 0
    total = 0

    def chk(label, got, want, tol=1e-6, is_bool=False):
        nonlocal passes, total
        total += 1
        if is_bool:
            ok = (got == want)
            rw.print("  [{}] {}".format("PASS" if ok else "FAIL", label))
        else:
            ok = abs(got / want - 1.0) < tol if want != 0 else abs(got) < 1e-12
            rw.print("  [{}] {}: {:.6g}  (ref {:.6g})".format(
                "PASS" if ok else "FAIL", label, got, want))
        if ok:
            passes += 1

    chk("T1: alpha not a free symbol in omega_photon^2", not s1['alpha_in_photon'], True, is_bool=True)
    chk("T2: alpha not a free symbol in omega_vortex^2", not s1['alpha_in_vortex'], True, is_bool=True)
    chk("T3: alpha(M=0) = 1 identically (SymPy residual 0)", s2['residual_zero'], True, is_bool=True)
    chk("T4: d(Lambda)/dM = 0 (cutoff is M-independent)", s3['dLambda_dM_zero'], True, is_bool=True)
    chk("T5: N_eff(minimal)=8 (RECHECK vs Part 83.3)", s4['N_minimal'], 8, is_bool=True)
    chk("T6: N_eff(two-phase)=10 (RECHECK vs Part 83.4)", s4['N_two_phase'], 10, is_bool=True)
    chk("T7: N_eff(+matter)=34 (RECHECK vs Part 83.5)", s4['N_matter'], 34, is_bool=True)
    chk("T8: G_ind/G(N_s=8) matches Part 83's 2.356 within 0.1%",
        s4['G_ind_over_G'], 2.356, tol=1e-3)
    chk("T9: target 6*pi lies within [N_minimal, N_matter] range",
        s4['target_in_range'], True, is_bool=True)
    chk("T10: hypothetical n^p correction = 1.0 for all tested p at M=0",
        all(abs(f - 1.0) < 1e-12 for f in s4['correction_factors']), True, is_bool=True)
    chk("T11: two-phase cutoff identical to single-phase (still M-independent)",
        s6['same_cutoff'] and s6['still_M_independent'], True, is_bool=True)
    chk("T12: T7 and T12 both verdict 'unchanged' (recorded as independent findings)",
        s5['both_negative'], True, is_bool=True)

    rw.print("")
    rw.print("  SCORE: {}/{} PASS".format(passes, total))
    return {'passes': passes, 'total': total, 'all_pass': passes == total}


