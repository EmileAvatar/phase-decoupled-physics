# PART 2: n_PDTP IS SOURCED BY M AND IDENTICALLY 1 AT M=0
# ===========================================================================

def verify_alpha_vacuum_limit(rw):
    """
    Part 98 Eq 98.2: alpha(r) = sqrt(1 - 2*G*M/(r*c^2)).
    Substitute M=0 (flat vacuum, no gravitating body) and simplify.
    """
    rw.section("PART 2: alpha -> 1 AT M=0 (FLAT VACUUM)")

    G, M, r, c = symbols('G M r c', positive=True)
    alpha_expr = sqrt(1 - 2*G*M/(r*c**2))                            # Eq 98.2

    alpha_at_M0 = simplify(alpha_expr.subs(M, 0))
    residual = simplify(alpha_at_M0 - 1)

    rw.print("  alpha(r) = sqrt(1 - 2*G*M/(r*c^2))               [Part 98, Eq 98.2]")
    rw.print("  alpha(M=0) = {}".format(alpha_at_M0))
    rw.print("  residual vs 1 = {}  [{}]".format(
        residual, "VERIFIED, alpha=1 identically" if residual == 0 else "FAIL"))
    rw.print("")
    rw.print("  n_PDTP = 1/alpha [Part 98, Eq 98.1] -> n_PDTP(M=0) = 1 identically,")
    rw.print("  for ALL r > 0. n_PDTP only deviates from 1 in the presence of a")
    rw.print("  gravitating mass M (weak-field form n_PDTP ~ 1 + GM/(rc^2), Eq 98.3).")

    return {'alpha_at_M0': alpha_at_M0, 'residual_zero': (residual == 0)}


