def verify_dispersion_no_alpha(rw):
    """
    Part 95 Eq 95.5 (photon/phonon) and Eq 95.7 (vortex/matter) dispersion
    relations, re-typed here. Check symbolically that 'alpha' does not
    appear as a free symbol in either -- they are built from (c, k) and
    (m_cond, c, hbar, k) only.
    """
    rw.section("PART 1: C1 DISPERSION RELATIONS (PART 95) -- NO alpha TERM")

    c, k, m_cond, hbar, alpha = symbols('c k m_cond hbar alpha', positive=True)

    omega_photon_sq = (c * k)**2                                    # Eq 95.5/95.6
    omega_vortex_sq = (m_cond * c**2 / hbar)**2 + c**2 * k**2        # Eq 95.7

    free_syms_photon = omega_photon_sq.free_symbols
    free_syms_vortex = omega_vortex_sq.free_symbols
    alpha_in_photon = alpha in free_syms_photon
    alpha_in_vortex = alpha in free_syms_vortex

    rw.print("  omega_photon^2 = (c*k)^2                        [Part 95, Eq 95.5]")
    rw.print("  free symbols: {}".format(free_syms_photon))
    rw.print("  alpha present: {}".format(alpha_in_photon))
    rw.print("")
    rw.print("  omega_vortex^2 = (m_cond*c^2/hbar)^2 + c^2*k^2   [Part 95, Eq 95.7]")
    rw.print("  free symbols: {}".format(free_syms_vortex))
    rw.print("  alpha present: {}".format(alpha_in_vortex))
    rw.print("")
    rw.print("  RESULT: neither C1 dispersion relation contains alpha (or n_PDTP)")
    rw.print("  as a variable. This is the dispersion the Sakharov vacuum sum is")
    rw.print("  built from (Part 74b/83) -- there is no alpha-dependent term for")
    rw.print("  a refractive-index correction to attach to.")

    return {'alpha_in_photon': alpha_in_photon, 'alpha_in_vortex': alpha_in_vortex}


