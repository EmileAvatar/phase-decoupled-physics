# PART 3: THE SAKHAROV CUTOFF HAS NO M DEPENDENCE
# ===========================================================================

def verify_cutoff_no_M_dependence(rw):
    """
    Part 74b/83 Eq: Lambda = m_cond*c/hbar. This is a property of the
    condensate (m_cond, the free A1 parameter), NOT of any test mass M.
    Confirm symbolically: d(Lambda)/dM = 0.
    """
    rw.section("PART 3: SAKHAROV CUTOFF Lambda HAS NO M DEPENDENCE")

    m_cond, c, hbar, M = symbols('m_cond c hbar M', positive=True)
    Lambda_expr = m_cond * c / hbar                                  # Part 74b Eq 74b.3

    dLambda_dM = diff(Lambda_expr, M)

    rw.print("  Lambda = m_cond*c/hbar                            [Part 74b, Eq 74b.3]")
    rw.print("  d(Lambda)/dM = {}".format(dLambda_dM))
    rw.print("")
    rw.print("  RESULT: Lambda contains no M at all -- the derivative is trivially 0.")
    rw.print("  The Sakharov one-loop calculation that fixes N_eff (Part 83) is a")
    rw.print("  flat-vacuum computation using THIS cutoff. Since n_PDTP is M-sourced")
    rw.print("  (Part 2) and Lambda is M-independent, there is no mechanism by which")
    rw.print("  n_PDTP could enter this specific calculation.")

    return {'dLambda_dM_zero': (dLambda_dM == 0)}


